export function getScenesForLocation(location?: string): Record<string, TimePeriod> {
  const loc = location?.toLowerCase();
  if (loc === 'kolkata') {
    return KOLKATA_SCENES;
  }
  if (loc === 'bangalore' || loc === 'bengaluru') {
    return BANGALORE_SCENES;
  }
  if (loc === 'mumbai' || loc === 'bombay') {
    return MUMBAI_SCENES;
  }
  return GENERIC_SCENES;
}

export function getSceneBgImage(period?: TimePeriod, variantIndex?: number | 'random'): string {
  if (!period) return '/scenes/generic/morning.webp';
  const images = period.bgImages && period.bgImages.length > 0 ? period.bgImages : [period.bgImage];
  if (images.length === 1) return images[0];

  if (variantIndex === 'random') {
    const randomIdx = Math.floor(Math.random() * images.length);
    return images[randomIdx];
  }
  if (typeof variantIndex === 'number') {
    const safeIdx = ((variantIndex % images.length) + images.length) % images.length;
    return images[safeIdx];
  }
  return images[0];
}

